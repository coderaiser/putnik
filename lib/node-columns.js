const toCamel = (name) => name.replace(/_([a-z])/g, (all, char) => char.toUpperCase());

// 'in' is a keyword of SQL
export const toColumn = (field) => field === 'in' ? 'in_' : field.replace(/[A-Z]/g, (char) => `_${char.toLowerCase()}`);
export const toField = (column) => column === 'in_' ? 'in' : toCamel(column);

export const parseColumns = (columns) => {
    const result = [];
    
    for (const word of columns.split(',')) {
        const [name, type] = word
            .trim()
            .split(' ');
        
        if (name)
            result.push({
                name,
                type,
            });
    }
    
    return result;
};
